/* DOG ARMY. KRAY Social strip (home): live posts from kray.space read through
   /api/social (their CORS allowlist blocks direct browser fetches). Cards are
   built with createElement — post text is user-generated, never parsed as HTML.
   Clicking a card opens the poster's inscription profile on kray.space. */
(function () {
  var FALLBACK = 'public/dog-army-mark.png';
  function ready(fn) {
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fn);
    else fn();
  }
  ready(function () {
    var strip = document.getElementById('krSocial');
    var track = document.getElementById('krSocialTrack');
    if (!strip || !track) return;
    var current = 'trending';
    var lastGood = 'trending';

    function card(p) {
      var a = document.createElement('a');
      a.className = 'social-card';
      a.href = p.url;
      a.target = '_blank';
      a.rel = 'noopener';
      var img = document.createElement('img');
      img.className = 'social-card-thumb';
      img.loading = 'lazy';
      img.alt = '';
      img.src = p.img || FALLBACK;
      img.addEventListener('error', function () { img.src = FALLBACK; }, { once: true });
      var body = document.createElement('span');
      body.className = 'social-card-body';
      var text = document.createElement('span');
      text.className = 'social-card-text';
      if (p.l2) {
        var badge = document.createElement('span');
        badge.className = 'social-card-l2';
        badge.textContent = 'L2';
        text.appendChild(badge);
      }
      text.appendChild(document.createTextNode(p.text || ''));
      var stats = document.createElement('span');
      stats.className = 'social-card-stats';
      var likes = document.createElement('span');
      likes.textContent = '❤️ ' + (p.likes || 0);
      var comments = document.createElement('span');
      comments.textContent = '💬 ' + (p.comments || 0);
      stats.appendChild(likes);
      stats.appendChild(comments);
      if (p.reward && p.reward.left > 0) {
        var reward = document.createElement('span');
        reward.className = 'social-card-reward';
        reward.textContent = '💰 ' + p.reward.amount.toLocaleString('en-US', { maximumFractionDigits: 5 }) + ' ' + p.reward.token;
        stats.appendChild(reward);
      }
      body.appendChild(text);
      body.appendChild(stats);
      a.appendChild(img);
      a.appendChild(body);
      return a;
    }

    var hasContent = false;
    var reduceMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    function setActiveChip(feed) {
      Array.prototype.forEach.call(strip.querySelectorAll('.soc-chip'), function (b) {
        b.classList.toggle('active', b.getAttribute('data-feed') === feed);
      });
    }

    function load(feed) {
      track.classList.add('no-anim');
      fetch('/api/social?feed=' + feed)
        .then(function (r) { return r.json(); })
        .then(function (d) {
          if (feed !== current) return;
          var posts = (d && d.success && d.posts) || [];
          if (!posts.length) throw new Error('empty');
          hasContent = true;
          lastGood = feed;
          strip.hidden = false;
          track.innerHTML = '';
          posts.forEach(function (p) { track.appendChild(card(p)); });
          /* duplicate set for the seamless -50% loop — decorative only, so it
             stays out of the tab order and screen readers. Skipped entirely
             under reduced motion, where the strip is a manual scroller. */
          if (!reduceMotion) {
            posts.forEach(function (p) {
              var dup = card(p);
              dup.setAttribute('aria-hidden', 'true');
              dup.tabIndex = -1;
              track.appendChild(dup);
            });
            track.classList.remove('no-anim');
          }
        })
        .catch(function () {
          if (feed !== current) return;
          if (!hasContent) { strip.hidden = true; return; }
          /* a failed toggle keeps the strip alive: fall back to what's
             already rendered and put the active chip back on the last feed
             that actually loaded */
          current = lastGood;
          setActiveChip(lastGood);
          track.classList.remove('no-anim');
        });
    }

    Array.prototype.forEach.call(strip.querySelectorAll('.soc-chip'), function (btn) {
      btn.addEventListener('click', function () {
        var feed = btn.getAttribute('data-feed');
        if (feed === current) return;
        current = feed;
        setActiveChip(feed);
        load(feed);
      });
    });

    load(current);
  });
})();

/* ---- nav scrollspy: acende em laranja a seção que você está lendo.
   Links diretos ganham .nav-here; seções dentro de um dropdown acendem
   o .navgroup pai. Só roda onde os anchors existem (a home). ---- */
(function () {
  if (!("IntersectionObserver" in window)) return;
  function init() {
    var links = document.querySelectorAll(
      ".navlinks a[href^='#'], .navgroup-menu a[href^='#']");
    if (!links.length) return;
    var map = {}; // id da seção -> elemento a acender (link ou grupo)
    Array.prototype.forEach.call(links, function (a) {
      var id = a.getAttribute("href").slice(1);
      /* "#top" é o link Home — no topo da página nada fica aceso */
      if (!id || id === "top" || !document.getElementById(id)) return;
      var grp = a.closest ? a.closest(".navgroup") : null;
      map[id] = grp || a;
    });
    var ids = Object.keys(map);
    if (!ids.length) return;
    var current = null;
    function clearCurrent() {
      if (current) { current.classList.remove("nav-here"); current = null; }
    }
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (!en.isIntersecting) return;
        var el = map[en.target.id];
        if (!el || el === current) return;
        clearCurrent();
        current = el;
        el.classList.add("nav-here");
      });
    }, { rootMargin: "-30% 0px -55% 0px" });
    ids.forEach(function (id) { io.observe(document.getElementById(id)); });
    /* de volta ao topo (Home) = nenhuma seção em leitura; apaga o destaque */
    window.addEventListener("scroll", function () {
      if (window.scrollY < 120) clearCurrent();
    }, { passive: true });
  }
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else { init(); }
})();

/* satspace — portal embutido (iframe só carrega no clique) + modal
   "o que é isso". Fechar o portal remove o iframe: a engine 3D para de
   rodar e não queima bateria de ninguém. */
(function () {
  function init() {
    var launch = document.getElementById("satLaunch");
    var portal = document.getElementById("satPortal");
    var frameBox = document.getElementById("satFrameBox");
    if (launch && portal && frameBox) {
      var closeBtn = document.getElementById("satPortalClose");
      launch.addEventListener("click", function () {
        if (!frameBox.querySelector("iframe")) {
          var f = document.createElement("iframe");
          /* /universo = satspace servido pelo nosso domínio (proxy). Mesma
             origem, então a página pai empresta a carteira pro iframe:
             a extensão KRAY só injeta em top-level, e o satspace faz
             polling de window.krayWallet a cada 1,5s até enxergar. */
          f.src = "/universo";
          f.title = "satspace";
          f.allow = "fullscreen; clipboard-write";
          f.setAttribute("allowfullscreen", "");
          /* sem allow-popups: nada dentro do embed abre aba externa */
          f.setAttribute("sandbox", "allow-scripts allow-same-origin allow-forms allow-pointer-lock");
          var tries = 0;
          function bridge() {
            try {
              if (f.contentWindow && window.krayWallet && !f.contentWindow.krayWallet) {
                f.contentWindow.krayWallet = window.krayWallet;
                try { f.contentWindow.dispatchEvent(new Event("krayWalletReady")); } catch (e) {}
              }
            } catch (e) { tries = 99; }
          }
          f.addEventListener("load", bridge);
          /* a extensão pode injetar depois do load; insiste por ~30s */
          var t = window.setInterval(function () {
            tries++;
            if (tries > 20 || !frameBox.querySelector("iframe")) { window.clearInterval(t); return; }
            bridge();
          }, 1500);
          frameBox.appendChild(f);
        }
        portal.hidden = false;
        launch.hidden = true;
        try { portal.scrollIntoView({ behavior: "smooth", block: "nearest" }); } catch (e) {}
      });
      if (closeBtn) closeBtn.addEventListener("click", function () {
        portal.hidden = true;
        launch.hidden = false;
        var f = frameBox.querySelector("iframe");
        if (f) f.remove();
      });
    }
    var what = document.getElementById("satWhat");
    var modal = document.getElementById("satModal");
    var scrim = document.getElementById("satScrim");
    if (!what || !modal || !scrim) return;
    var mClose = document.getElementById("satModalClose");
    function shut() {
      modal.hidden = true; scrim.hidden = true;
      document.body.style.overflow = "";
    }
    what.addEventListener("click", function () {
      modal.hidden = false; scrim.hidden = false;
      document.body.style.overflow = "hidden";
      modal.scrollTop = 0;
    });
    scrim.addEventListener("click", shut);
    if (mClose) mClose.addEventListener("click", shut);
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" && !modal.hidden) shut();
    });
  }
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else { init(); }
})();

