(function () {
  var ORDER = ["en", "pt", "es", "it", "zh"];
  var NAMES = { en: "EN", pt: "PT", es: "ES", it: "IT", zh: "中文" };
  var FLAGS = { en: "public/flag-us.svg", pt: "public/flag-br.svg", es: "public/flag-es.svg" };
  var LABELS = { en: "English", pt: "Português", es: "Español", it: "Italiano", zh: "中文" };
  var DICT = window.DOG_I18N || {};
  var baseline = {};

  function els() { return document.querySelectorAll("[data-i18n]"); }
  function has(lang) { return lang === "en" || !!DICT[lang]; }

  function apply(lang) {
    var d = DICT[lang] || {};
    els().forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      var v = (lang === "en") ? baseline[k] : (d[k] != null ? d[k] : baseline[k]);
      if (v != null) el.innerHTML = v;
    });
    document.documentElement.setAttribute("lang", lang === "zh" ? "zh-CN" : (lang === "pt" ? "pt-BR" : lang));
    try { sessionStorage.setItem("dogLang", lang); } catch (e) {}
    try { localStorage.setItem("dogLang", lang); } catch (e) {}
    /* dynamic renderers (planos.js etc.) re-render on this signal, so a language
       switch never leaves JS-built content behind in the old language */
    try { document.dispatchEvent(new CustomEvent("dog:lang", { detail: { lang: lang } })); } catch (e) {}
    var sw = document.getElementById("langsw");
    if (sw) {
      var cur = sw.querySelector(".langsw-cur");
      if (cur && FLAGS[lang]) cur.src = FLAGS[lang];
      var trig = sw.querySelector(".langsw-trigger");
      if (trig) trig.setAttribute("aria-label", "Language: " + (LABELS[lang] || lang));
      sw.querySelectorAll(".langsw-opt").forEach(function (b) {
        b.classList.toggle("active", b.getAttribute("data-lang") === lang);
      });
    }
  }

  function pick() {
    // ?lang= always wins (shared links). A choice made via the switcher persists
    // across tabs and visits (localStorage; sessionStorage kept as the per-tab
    // mirror that page scripts read). First visit with no choice: follow the
    // browser language, so a PT-BR soldier lands in PT and nothing mixes.
    try {
      var q = new URLSearchParams(location.search).get("lang");
      if (q && has(q)) return q;
    } catch (e) {}
    try {
      var s = sessionStorage.getItem("dogLang");
      if (s && has(s)) return s;
    } catch (e) {}
    try {
      var l = localStorage.getItem("dogLang");
      if (l && has(l)) return l;
    } catch (e) {}
    try {
      var nav = String((navigator.languages && navigator.languages[0]) || navigator.language || "").toLowerCase();
      if (nav.indexOf("pt") === 0 && has("pt")) return "pt";
      if (nav.indexOf("es") === 0 && has("es")) return "es";
    } catch (e) {}
    return "en";
  }

  function build() {
    var sw = document.getElementById("langsw");
    if (!sw) return;
    var opts = "";
    ORDER.forEach(function (lang) {
      if (!has(lang)) return;
      var label = LABELS[lang] || NAMES[lang];
      opts += '<button type="button" role="menuitem" class="langsw-opt" data-lang="' + lang +
        '"><img src="' + FLAGS[lang] + '" width="20" height="14" alt="" loading="lazy" decoding="async"><span>' +
        label + '</span></button>';
    });
    sw.innerHTML =
      '<button type="button" class="langsw-trigger" aria-haspopup="true" aria-expanded="false" aria-label="Language">' +
      '<img class="langsw-cur" alt="" width="20" height="14"><span class="langsw-caret" aria-hidden="true">\u25be</span></button>' +
      '<div class="langsw-menu" role="menu">' + opts + '</div>';
    var trigger = sw.querySelector(".langsw-trigger");
    function close() { sw.classList.remove("open"); trigger.setAttribute("aria-expanded", "false"); }
    trigger.addEventListener("click", function (e) {
      e.stopPropagation();
      var open = !sw.classList.contains("open");
      sw.classList.toggle("open", open);
      trigger.setAttribute("aria-expanded", open ? "true" : "false");
    });
    sw.querySelectorAll(".langsw-opt").forEach(function (b) {
      b.addEventListener("click", function () { apply(b.getAttribute("data-lang")); close(); });
    });
    document.addEventListener("click", function (e) { if (!sw.contains(e.target)) close(); });
    document.addEventListener("keydown", function (e) { if (e.key === "Escape") close(); });
  }

  function init() {
    els().forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      if (!(k in baseline)) baseline[k] = el.innerHTML;
    });
    build();
    apply(pick());
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();

